        <p class="meta">Última actualización: 27 de agosto de 2026</p>

        <p>Esta política explica qué datos maneja la aplicación <strong>A.S New Castle</strong> (la «App»), operada por
        <strong>ASOCIAȚIA SPORTIVĂ NEW CASTLE</strong> (el «Club»), asociación deportiva sin fines de lucro registrada en
        Voluntari, Ilfov, Rumania (CIF 53035344). La App es una herramienta interna de gestión del club de fútbol amateur:
        convocatorias, asistencia, cuotas y chat del equipo.</p>

        <h2>Qué datos recopilamos</h2>
        <ul>
            <li><strong>Número de teléfono</strong>: para iniciar sesión (mediante un código de un solo uso) e identificarte en tu club. No usamos contraseña ni exigimos email.</li>
            <li><strong>Datos del perfil</strong>: tu nombre, número de camiseta, posición, pie hábil y disponibilidad, que vos mismo cargás.</li>
            <li><strong>Actividad del club</strong>: tus confirmaciones de asistencia a partidos y entrenamientos, votaciones de figura y calificaciones (anónimas).</li>
            <li><strong>Mensajes y fotos</strong> que enviás al chat del vestuario.</li>
            <li><strong>Cuotas y pagos</strong>: el estado de tus cuotas. Los pagos con tarjeta los procesa Stripe; la App no almacena datos de tu tarjeta.</li>
            <li><strong>Identificador de notificaciones</strong>: un token del dispositivo para enviarte avisos push (por ejemplo, cuando se crea un partido).</li>
        </ul>

        <h2>Para qué usamos los datos</h2>
        <ul>
            <li>Organizar al equipo: avisarte de partidos y entrenamientos y registrar quién asiste.</li>
            <li>Permitir el chat del vestuario y las votaciones post-partido.</li>
            <li>Llevar el estado de las cuotas y la caja del club.</li>
            <li>Enviarte notificaciones relacionadas con la actividad de tu club.</li>
        </ul>
        <p>No vendemos tus datos ni los usamos para publicidad.</p>

        <h2>Con quién se comparten</h2>
        <p>Solo con los proveedores necesarios para que la App funcione:</p>
        <ul>
            <li><strong>Stripe</strong> — procesamiento de pagos de las cuotas.</li>
            <li><strong>Google Firebase (Cloud Messaging)</strong> — envío de notificaciones push.</li>
            <li><strong>Microsoft Azure (Translator)</strong> — traducción, solo del mensaje que elegís traducir.</li>
            <li><strong>Twilio</strong> — envío del código de acceso y avisos por WhatsApp (cuando esté habilitado).</li>
            <li><strong>Laravel Forge / proveedor de alojamiento</strong> — servidores donde corre la App.</li>
        </ul>
        <p>Tus datos solo son visibles para los miembros de tu propio club. Tu número de teléfono nunca se muestra a otros jugadores.</p>

        <h2>Conservación y borrado de tus datos</h2>
        <p>Conservamos tus datos mientras seas miembro de un club en la App. Podés borrar tu cuenta y todos tus datos vos mismo, en cualquier momento y de forma inmediata, desde <strong>Perfil → Eliminar mi cuenta</strong> dentro de la App. Al hacerlo se eliminan tu perfil, tus confirmaciones de asistencia, tus cuotas y pagos, tus votaciones y calificaciones, y los tokens de notificación; tus mensajes del vestuario se anonimizan. También podés pedirnos el borrado por email a <a href="mailto:avocode.srl@gmail.com">avocode.srl@gmail.com</a>.</p>

        <h2>Seguridad</h2>
        <p>La comunicación con la App está cifrada (HTTPS). El acceso a los datos de cada club está aislado del resto. Aun así, ningún sistema es 100% infalible.</p>

        <h2>Tus derechos</h2>
        <p>Podés acceder, corregir o eliminar tus datos. El borrado de la cuenta está disponible directamente en la App (<strong>Perfil → Eliminar mi cuenta</strong>); para cualquier otro pedido escribinos a
        <a href="mailto:avocode.srl@gmail.com">avocode.srl@gmail.com</a>.</p>

        <h2>Menores</h2>
        <p>La App está pensada para el uso interno del plantel del club. No está dirigida a menores de 13 años.</p>

